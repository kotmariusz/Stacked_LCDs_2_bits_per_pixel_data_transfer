/* USER CODE BEGIN PD */

/* How long each frame is held, in milliseconds. */
/* How long each frame is actually ON SCREEN, in milliseconds - the drawing
 * time is measured and taken out of the wait, so this is the real figure and
 * not a delay with an unknown extra on top.
 *
 * It used to be just the delay, which is misleading: writing both panels takes
 * about 120 ms at 1.1 MHz, so a recording made with DWELL_MS 200 was measured
 * off the blank markers at 323 ms a frame. That still decoded nothing - the
 * liquid crystal had not finished moving when the next frame arrived, so the
 * cells that changed were photographed mid-transition and read as the wrong
 * state, even though the picture looked perfectly sharp.
 *
 * 1500 is known to work. Going faster is worth trying, but do it in steps and
 * check each one decodes: somewhere below about a second the panel stops
 * keeping up, and the failure looks like a sharp photograph that will not
 * decode rather than anything obviously blurred. */
#define DWELL_MS      1500

/* Show one solid frame between cycles, as a visible restart marker. */
#define GAP_FRAME     1

/* Cell size and marker setting come from the generated header, so the
 * firmware and the notebook cannot drift apart. */
#define CELL_PX       PIC_CELL_PX
#define USE_MARKERS   PIC_USE_MARKERS

#define CODE_W        (ST7567_WIDTH  / CELL_PX)
#define CODE_H        (ST7567_HEIGHT / CELL_PX)

#define LCD_DC_PORT     GPIOA
#define LCD_DC_PIN      GPIO_PIN_4

#define LCD1_CS_PORT    GPIOA
#define LCD1_CS_PIN     GPIO_PIN_3
#define LCD1_RST_PORT   GPIOA
#define LCD1_RST_PIN    GPIO_PIN_2

#define LCD2_CS_PORT    GPIOA
#define LCD2_CS_PIN     GPIO_PIN_1
#define LCD2_RST_PORT   GPIOA
#define LCD2_RST_PIN    GPIO_PIN_0

#define LCD_CONTRAST    100

/* Panel 2 runs with the segment direction reversed, so its visible window
 * starts four columns further along. Correcting the ADDRESS rather than the
 * drawing means nothing is clipped at the edges. */
#define PANEL1_COL_OFFSET   0
#define PANEL2_COL_OFFSET   4


/* ---- Resilience ---------------------------------------------------------
 * The frame used to be written to the panels exactly once, at boot. That is
 * precisely why a fault could look permanent and yet be different after every
 * reset: one corrupted byte on the SPI wire during that single write stays on
 * the glass until the next restart, and the next restart corrupts a different
 * byte. Nothing ever overwrites it.
 *
 * Writing the frame again every REFRESH_MS costs nothing on a static display
 * and turns a permanent defect into one that clears itself in well under a
 * second. Re-initialising every REINIT_MS covers the rarer case of a COMMAND
 * byte being hit, which can leave a whole page sitting at the wrong column.
 *
 * This is a safety net, not a cure. Fewer errors in the first place come from
 * SPI_PRESCALER below and from shorter, tidier wiring.
 */
#define REFRESH_MS      400

/* Re-initialise the panels once per cycle. OFF by default: it blanks both
 * panels for about a second while they reset, which is disruptive if you are
 * filming, and it buys very little - the bring-up was measured to converge to
 * identical registers from 200 randomly corrupted starting states, so there is
 * no stuck state for it to rescue. Turn it on only if you see a fault that a
 * redraw never clears. */
#define REINIT_EACH_CYCLE  0

/* SPI clock, set at boot so CubeMX does not have to be regenerated to change
 * it. On a 72 MHz APB2: _16 = 4.5 MHz (where this started), _64 = 1.1 MHz,
 * _128 = 560 kHz. Two panels hanging off the same SCK and SDI through
 * breadboard jumpers is a lot of capacitance for 4.5 MHz; the panel does not
 * care how slow it is, a static frame has all the time in the world. */
#define SPI_PRESCALER   SPI_BAUDRATEPRESCALER_64

/* USER CODE END PD */

/* USER CODE BEGIN PV */
static ST7567_t lcd1;
static ST7567_t lcd2;
/* USER CODE END PV */

void SystemClock_Config(void);
/* USER CODE BEGIN PFP */
static void panels_bring_up(void);
static void draw_frame(const uint8_t *frame);
static void draw_solid(uint8_t value);
/* USER CODE END PFP */

/* USER CODE BEGIN 0 */

#if USE_MARKERS
/* Three corners plus a diagonal partner. The asymmetry makes the arrangement
 * chiral, so every rotation AND mirror is distinguishable and the reader can
 * work out which way up a frame is without being told. */
static int marker_state(uint16_t row, uint16_t col)
{
  if (row == 0 && col == 0)             return 0;
  if (row == 0 && col == CODE_W - 1)    return 1;
  if (row == CODE_H - 1 && col == 0)    return 2;
  if (row == CODE_H - 2 && col == 1)    return 3;
  return -1;
}
#endif

/* Change only the clock divider, in place. Deliberately not HAL_SPI_DeInit()
 * followed by HAL_SPI_Init(): DeInit calls HAL_SPI_MspDeInit(), which switches
 * the SPI clock off and hands PA5 and PA7 back as plain GPIO - and those two
 * pins are shared with both panels. The SPI_BAUDRATEPRESCALER_* constants are
 * already positioned for the BR field of CR1, so they drop straight in. */
static void spi_set_speed(uint32_t prescaler)
{
  __HAL_SPI_DISABLE(&hspi1);
  MODIFY_REG(hspi1.Instance->CR1, SPI_CR1_BR, prescaler);
  hspi1.Init.BaudRatePrescaler = prescaler;
  __HAL_SPI_ENABLE(&hspi1);
}

/* ---- Cell geometry -------------------------------------------------------
 * Both panels are drawn at the same scale: cell (cx, cy) is simply the
 * CELL_PX square at (cx*CELL_PX, cy*CELL_PX) on whichever panels its bits ask
 * for. Every cell is exactly CELL_PX across, every edge meets its neighbour,
 * and the grid runs flush to the glass on both panels.
 */
static void fill_cell(ST7567_t *d, uint16_t cx, uint16_t cy)
{
  ST7567_FillRect(d, (uint8_t)(cx * CELL_PX), (uint8_t)(cy * CELL_PX),
                  CELL_PX, CELL_PX, 1);
}

static void draw_cell(uint16_t index, uint8_t value)
{
  uint16_t cx = index % CODE_W;
  uint16_t cy = index / CODE_W;

  if (value & 0x01) fill_cell(&lcd1, cx, cy);
  if (value & 0x02) fill_cell(&lcd2, cx, cy);
}

/* Bring both panels up in a way that survives a warm reset.
 *
 * 1. Between the MCU reset and MX_GPIO_Init(), every pin is a floating input.
 *    The panels never lose power on a warm reset, so they are still listening,
 *    and whatever they pick up in that window can leave one mid-command. Both
 *    chip selects are driven HIGH before anything else happens.
 *
 * 2. Both panels share SCK, SDI and DC. If one chip select is low while the
 *    other panel is being set up, BOTH receive that panel's commands -
 *    including the wrong segment direction and column offset. CubeMX must have
 *    PA3 and PA1 set to an initial level of High.
 *
 * 3. On a cold start the panel supply may still be rising while the MCU is
 *    already running, so early commands are simply ignored.
 *
 * Initialising twice is cheap insurance: the second pass runs with everything
 * powered and quiet, so it lands even if the first was disturbed. */
static void panels_bring_up(void)
{
  HAL_GPIO_WritePin(LCD1_CS_PORT, LCD1_CS_PIN, GPIO_PIN_SET);
  HAL_GPIO_WritePin(LCD2_CS_PORT, LCD2_CS_PIN, GPIO_PIN_SET);
  HAL_GPIO_WritePin(LCD_DC_PORT,  LCD_DC_PIN,  GPIO_PIN_SET);

  HAL_GPIO_WritePin(LCD1_RST_PORT, LCD1_RST_PIN, GPIO_PIN_RESET);
  HAL_GPIO_WritePin(LCD2_RST_PORT, LCD2_RST_PIN, GPIO_PIN_RESET);
  HAL_Delay(50);
  HAL_GPIO_WritePin(LCD1_RST_PORT, LCD1_RST_PIN, GPIO_PIN_SET);
  HAL_GPIO_WritePin(LCD2_RST_PORT, LCD2_RST_PIN, GPIO_PIN_SET);
  HAL_Delay(150);

  for (int pass = 0; pass < 2; pass++) {
    ST7567_Init(&lcd1);
    HAL_Delay(20);
    ST7567_Init(&lcd2);
    HAL_Delay(20);
  }
}

/* Walk the grid in reading order. Reserved cells get their marker state; every
 * other cell takes the next two bits of the frame. Packing around the markers
 * is what stops them colliding with the header. */
static void draw_frame(const uint8_t *frame)
{
  ST7567_Clear(&lcd1);
  ST7567_Clear(&lcd2);

  uint16_t bit = 0;

  for (uint16_t row = 0; row < CODE_H; row++) {
    for (uint16_t col = 0; col < CODE_W; col++) {
      uint16_t index = (uint16_t)(row * CODE_W + col);

#if USE_MARKERS
      int mk = marker_state(row, col);
      if (mk >= 0) {
        draw_cell(index, (uint8_t)mk);
        continue;
      }
#endif
      uint16_t byte_i = (uint16_t)(bit >> 3);
      uint8_t  shift  = (uint8_t)(6 - (bit & 7));
      uint8_t  value  = (byte_i < PIC_FRAME_BYTES)
                        ? (uint8_t)((frame[byte_i] >> shift) & 0x03) : 0;
      draw_cell(index, value);
      bit = (uint16_t)(bit + 2);
    }
  }

  ST7567_Update(&lcd1);
  ST7567_Update(&lcd2);
}

/* One flat state across the whole grid. Carries no data - it is the visible
 * marker for where a cycle restarts. */
static void draw_solid(uint8_t value)
{
  ST7567_Clear(&lcd1);
  ST7567_Clear(&lcd2);
  for (uint16_t row = 0; row < CODE_H; row++) {
    for (uint16_t col = 0; col < CODE_W; col++) {
      draw_cell((uint16_t)(row * CODE_W + col), value);
    }
  }
  ST7567_Update(&lcd1);
  ST7567_Update(&lcd2);
}

/* USER CODE END 0 */

int main(void)
{
  HAL_Init();
  SystemClock_Config();
  MX_GPIO_Init();
  MX_SPI1_Init();

  /* USER CODE BEGIN 2 */

  lcd1.hspi     = &hspi1;
  lcd1.cs_port  = LCD1_CS_PORT;   lcd1.cs_pin  = LCD1_CS_PIN;
  lcd1.dc_port  = LCD_DC_PORT;    lcd1.dc_pin  = LCD_DC_PIN;
  lcd1.rst_port = LCD1_RST_PORT;  lcd1.rst_pin = LCD1_RST_PIN;
  lcd1.contrast   = LCD_CONTRAST;
  lcd1.col_offset = PANEL1_COL_OFFSET;
  lcd1.adc_cmd  = 0xA0;
  lcd1.com_cmd  = 0xC0;

  lcd2.hspi     = &hspi1;
  lcd2.cs_port  = LCD2_CS_PORT;   lcd2.cs_pin  = LCD2_CS_PIN;
  lcd2.dc_port  = LCD_DC_PORT;    lcd2.dc_pin  = LCD_DC_PIN;
  lcd2.rst_port = LCD2_RST_PORT;  lcd2.rst_pin = LCD2_RST_PIN;
  lcd2.contrast   = LCD_CONTRAST;
  lcd2.col_offset = PANEL2_COL_OFFSET;
  lcd2.adc_cmd  = 0xA1;
  lcd2.com_cmd  = 0xC0;

  spi_set_speed(SPI_PRESCALER);
  panels_bring_up();

  /* USER CODE END 2 */

  /* USER CODE BEGIN WHILE */
  while (1)
  {
    for (uint16_t i = 0; i < PIC_FRAME_COUNT; i++) {
      /* Write each frame more than once while it is being held. A write damaged
       * on the wire is then repaired within REFRESH_MS instead of standing for
       * the whole dwell - which, with one write per frame, is how a single bad
       * byte used to cost a whole chunk. A photograph that happens to catch a
       * rewrite in progress simply fails its CRC and is skipped.
       *
       * The clock is read rather than assumed, so the time spent drawing comes
       * out of the wait instead of being added to it. */
      uint32_t started = HAL_GetTick();
      for (;;) {
        draw_frame(pic_frames[i]);
        uint32_t spent = HAL_GetTick() - started;
        if (spent >= DWELL_MS) {
          break;
        }
        uint32_t left = DWELL_MS - spent;
        HAL_Delay(left < REFRESH_MS ? left : REFRESH_MS);
        if ((uint32_t)(HAL_GetTick() - started) >= DWELL_MS) {
          break;
        }
      }
    }
#if GAP_FRAME
    {
      uint32_t started = HAL_GetTick();
      draw_solid(3);
      uint32_t spent = HAL_GetTick() - started;
      if (spent < DWELL_MS) {
        HAL_Delay(DWELL_MS - spent);
      }
    }
#endif
#if REINIT_EACH_CYCLE
    panels_bring_up();
  #endif
    /* USER CODE END WHILE */
    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

/**
  * @brief System Clock Configuration
  * @retval None
  */
void SystemClock_Config(void)
{
  RCC_OscInitTypeDef RCC_OscInitStruct = {0};
  RCC_ClkInitTypeDef RCC_ClkInitStruct = {0};

  RCC_OscInitStruct.OscillatorType = RCC_OSCILLATORTYPE_HSE;
  RCC_OscInitStruct.HSEState = RCC_HSE_ON;
  RCC_OscInitStruct.HSEPredivValue = RCC_HSE_PREDIV_DIV1;
  RCC_OscInitStruct.HSIState = RCC_HSI_ON;
  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_ON;
  RCC_OscInitStruct.PLL.PLLSource = RCC_PLLSOURCE_HSE;
  RCC_OscInitStruct.PLL.PLLMUL = RCC_PLL_MUL9;
  if (HAL_RCC_OscConfig(&RCC_OscInitStruct) != HAL_OK)
  {
    Error_Handler();
  }

  RCC_ClkInitStruct.ClockType = RCC_CLOCKTYPE_HCLK|RCC_CLOCKTYPE_SYSCLK
                              |RCC_CLOCKTYPE_PCLK1|RCC_CLOCKTYPE_PCLK2;
  RCC_ClkInitStruct.SYSCLKSource = RCC_SYSCLKSOURCE_PLLCLK;
  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV1;
  RCC_ClkInitStruct.APB1CLKDivider = RCC_HCLK_DIV2;
  RCC_ClkInitStruct.APB2CLKDivider = RCC_HCLK_DIV1;

  if (HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_2) != HAL_OK)
  {
    Error_Handler();
  }
}

void Error_Handler(void)
{
  __disable_irq();
  while (1)
  {
  }
}
